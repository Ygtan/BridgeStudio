# 4. 对比报告
# ---------------------------------------------------------------------------

def _fmt(x, width: int = 16) -> str:
    return "{:>{w}.8g}".format(float(x), w=width)


def compare(spec, fem: dict, adisp: dict, areac: dict, aelem: dict,
            *, stem: str, n_spans: int, tol: float = 1e-3) -> tuple[str, bool]:
    """生成对比报告文本，返回 (报告, 是否全部通过)。"""
    et = spec.elem_types[0]
    mat = {m.id: m for m in spec.materials}.get(et.mat) or spec.materials[0]
    EI = float(mat.E) * float(et.I)
    xs = [float(n.x) for n in spec.nodes]
    total = max(xs) - min(xs)
    L = total / n_spans
    q = abs(float(spec.elem_loads[0].q))
    supports = sorted({int(b.node) for b in spec.boundaries
                       if "UY" in _dof_list(b.dofs)})
    R_th, M_sup_th, _, M_pos_th = theory(n_spans, L, q, EI, 0.0)

    lines: list[str] = []
    ok_all = True
    lines.append("=" * 78)
    lines.append("连续梁算例：BridgeStudio 前处理 -> FEM-Eigen / ANSYS 18.0 三方校核")
    lines.append("=" * 78)
    lines.append("算例编号      : " + stem)
    lines.append("跨数 / 单跨   : {} 跨 x {:.3f} m （总长 {:.3f} m）".format(n_spans, L, total))
    lines.append("单元 / 节点   : {} 个 2D BEAM / {} 节点，单元长 {:.3f} m".format(
        len(spec.elements), len(spec.nodes), total / len(spec.elements)))
    lines.append("材料 / 截面   : {} E={:.6g} Pa ; A={:.6g} m2  I={:.6g} m4  H={:.6g} m".format(
        mat.name, mat.E, et.A, et.I, et.H))
    lines.append("荷载          : 全桥均布 q={:.6g} N/m 向下；自重关闭（*GRAVITY 0 0 / 无 ACEL）".format(q))
    lines.append("支座节点      : " + ", ".join(map(str, supports)))
    lines.append("判定容差      : 相对误差 <= {:.3g} （沿用 tests/benchmark/ansys 的 rtol）".format(tol))
    lines.append("")

    def check(label, got, ref, *, atol=1e-9) -> None:
        nonlocal ok_all
        d = abs(got - ref)
        rel = d / abs(ref) if abs(ref) > atol else d
        ok = d <= atol + tol * abs(ref)
        ok_all &= ok
        lines.append("  {:<30s} {:>18s} {:>18s} {:>11s}  {}".format(
            label, _fmt(got), _fmt(ref), "{:.2e}".format(rel),
            "PASS" if ok else "FAIL"))

    # --- 1. 节点竖向位移 ---
    lines.append("-" * 78)
    lines.append("[1] 节点竖向位移 UY (m，向下为负)  FEM-Eigen vs ANSYS")
    lines.append("  {:<30s} {:>18s} {:>18s} {:>11s}  {}".format(
        "指标", "实测", "限值", "相对误差", "判定"))
    all_uy, max_abs, max_rel, worst = [], 0.0, 0.0, None
    for n in spec.nodes:
        i = int(n.id)
        vf = fem["disp"].get(i, {}).get("v")
        va = adisp.get(i, [None] * 4)[1] if i in adisp else None
        if vf is None or va is None:
            continue
        d = abs(vf - va)
        rel = d / max(abs(va), 1e-30)
        all_uy.append((i, vf, va, d, rel))
        if d > max_abs:
            max_abs = d
        if rel > max_rel:
            max_rel, worst = rel, i
    # 用相对量级判据（固定绝对阈值会随模型尺度误判）
    scale = max(abs(v[1]) for v in all_uy) or 1.0
    disp_ok = max_abs <= tol * scale
    ok_all &= disp_ok
    lines.append("  {:<30s} {:>18s} {:>18s} {:>11s}  {}".format(
        "最大差 / 最大位移", _fmt(max_abs / scale), _fmt(tol), "",
        "PASS" if disp_ok else "FAIL"))
    lines.append("  全 {} 节点 UY 最大绝对差 {:.6e} m（最大位移量级 {:.6e} m）".format(
        len(all_uy), max_abs, scale))
    lines.append("  注：nm 级差异来自两个程序线性方程组求解器的舍入，非建模差异")
    lines.append("  最大绝对差节点: {}  最大相对差节点: {}".format(
        max(all_uy, key=lambda r: r[3])[0] if all_uy else "-", worst))
    # 关键节点
    for i in sorted({1, int(len(spec.nodes) // (2 * n_spans)) + 1,
                     int(len(spec.nodes) // n_spans) + 1, len(spec.nodes)}):
        if i in fem["disp"] and i in adisp:
            vf, va = fem["disp"][i]["v"], adisp[i][1]
            lines.append("  节点 {:>3d} x={:>7.2f} m : FEM {:>16.8e}  ANSYS {:>16.8e}  差 {:>10.2e}".format(
                i, float(spec.nodes[i - 1].x), vf, va, abs(vf - va)))

    # 闭式解（仅两跨，逐点）
    if n_spans == 2:
        lines.append("")
        lines.append("[1b] 与 Euler-Bernoulli 闭式解逐点对比（左跨 v(x)=q(L^3x-3Lx^3+2x^4)/(48EI)）")
        dmax, xworst = 0.0, 0.0
        for n in spec.nodes:
            x = float(n.x) - min(xs)
            if x > L + 1e-9:
                x = 2.0 * L - x
            _, _, vth, _ = theory(2, L, q, EI, x)
            vf = fem["disp"].get(int(n.id), {}).get("v")
            if vf is None:
                continue
            d = abs(-vf - vth)
            if d > dmax:
                dmax, xworst = d, x
        vmax_th = 0.0054161 * q * L ** 4 / EI
        rel_th = dmax / vmax_th
        th_ok = rel_th <= 1e-3
        ok_all &= th_ok
        lines.append("  最大绝对偏差 {:.6e} m （x={:.3f} m），最大理论挠度 {:.6e} m，相对 {:.3e}  {}".format(
            dmax, xworst, vmax_th, rel_th, "PASS" if th_ok else "FAIL"))

    # --- 2. 支座反力 ---
    lines.append("")
    lines.append("-" * 78)
    lines.append("[2] 支座竖向反力 (N，向上为正)  FEM-Eigen / ANSYS / 闭式解")
    lines.append("  {:<12s} {:>18s} {:>18s} {:>18s} {:>11s}  {}".format(
        "支座节点", "FEM-Eigen", "ANSYS", "闭式解", "相对误差", "判定"))
    for k, nd in enumerate(supports):
        rf = fem["reaction"].get((nd, 2), 0.0)
        ra = areac.get(nd, [0.0] * 4)[1] if nd in areac else 0.0
        rt = R_th[k]
        d = abs(rf - rt)
        rel = d / abs(rt)
        ok = rel <= tol and abs(ra - rt) / abs(rt) <= tol
        ok_all &= ok
        lines.append("  {:<12d} {:>18s} {:>18s} {:>18s} {:>11s}  {}".format(
            nd, _fmt(rf), _fmt(ra), _fmt(rt), "{:.2e}".format(rel),
            "PASS" if ok else "FAIL"))
    sum_f = sum(fem["reaction"].get((nd, 2), 0.0) for nd in supports)
    sum_a = sum(areac.get(nd, [0.0] * 4)[1] for nd in supports)
    lines.append("  反力合计: FEM {:.8g} N ; ANSYS {:.8g} N ; 总荷载 q*Ltot {:.8g} N".format(
        sum_f, sum_a, q * total))

    # --- 3. 弯矩 ---
    lines.append("")
    lines.append("-" * 78)
    lines.append("[3] 单元端弯矩 (N*m)")
    # 用中支座两侧的端弯矩与闭式解对比，顺便判定 FEM / ANSYS 符号约定
    mid_sup = supports[1]
    e_left = mid_sup - 1
    e_right = mid_sup
    fm = fem["force"].get(e_left, {})
    am = aelem.get(e_left, [0.0] * 7)
    fem_M = fm.get("M2", 0.0)          # FEM: 单元 j 端
    ans_M = am[5]                      # ANSYS: 单元 j 端 SMISC 12（CSV 第 6 个数值）
    lines.append("  中支座左邻单元 {} 的 j 端弯矩: FEM M2={:.8g} ; ANSYS SMISC12={:.8g} ; 闭式解={:.8g}".format(
        e_left, fem_M, ans_M, M_sup_th))
    same = abs(abs(fem_M) - abs(ans_M)) <= 0.01 * max(abs(ans_M), 1.0)
    lines.append("  幅值一致性: {}（两者符号约定{}）".format(
        "一致" if same else "不一致", "相同" if fem_M * ans_M > 0 else "相反"))
    dl = abs(abs(fem_M) - abs(M_sup_th)) / abs(M_sup_th)
    da = abs(abs(ans_M) - abs(M_sup_th)) / abs(M_sup_th)
    bend_ok = dl <= tol and da <= tol and same
    ok_all &= bend_ok
    lines.append("  {:<30s} {:>18s} {:>18s} {:>11s}  {}".format(
        "中支座负弯矩相对闭式解", "{:.2e}".format(dl), "{:.2e}".format(da), "",
        "PASS" if bend_ok else "FAIL"))
    # 全部单元端弯矩幅值对比（自动按 FEM 与 ANSYS 的符号约定对齐）
    # ANSYS elem CSV 列: [NI, VI, MI, NJ, VJ, MJ] -> 索引 0..5
    # FEM-Eigen 列: N1 N2 V1 M1 V2 M2
    # 弯矩: FEM M1 <-> ANSYS MI(2), FEM M2 <-> ANSYS MJ(5)
    # 剪力: FEM V1 <-> ANSYS VI(1), FEM V2 <-> ANSYS VJ(4)，两者符号约定相反，取幅值
    pairs = [(abs(fem["force"][e]["M1"]), abs(aelem[e][2]),
              abs(fem["force"][e]["M2"]), abs(aelem[e][5]),
              abs(fem["force"][e]["V1"]), abs(aelem[e][1]),
              abs(fem["force"][e]["V2"]), abs(aelem[e][4]))
             for e in sorted(fem["force"]) if e in aelem]
    if pairs:
        err_m = max(max(abs(a - b), abs(c - d)) for a, b, c, d, *_ in pairs)
        err_v = max(max(abs(p[4] - p[5]), abs(p[6] - p[7])) for p in pairs)
        scale_m = max(max(p[0], p[1], p[2], p[3]) for p in pairs) or 1.0
        scale_v = max(max(p[4], p[5], p[6], p[7]) for p in pairs) or 1.0
        m_ok, v_ok = err_m / scale_m <= tol, err_v / scale_v <= tol
        ok_all &= (m_ok and v_ok)
        lines.append("  {} 个单元 i/j 端弯矩幅值: 最大绝对差 {:.6e} N*m，相对 {:.3e}  {}".format(
            len(pairs), err_m, err_m / scale_m, "PASS" if m_ok else "FAIL"))
        lines.append("  {} 个单元 i/j 端剪力幅值: 最大绝对差 {:.6e} N，相对 {:.3e}  {}".format(
            len(pairs), err_v, err_v / scale_v, "PASS" if v_ok else "FAIL"))
        lines.append("  剪力符号约定: FEM-Eigen V 与 ANSYS SMISC 2/8 反号（幅值一致，属约定差异）")
    lines.append("  最大正弯矩闭式解 {:.8g} N*m（用于量级核查）".format(M_pos_th))

    lines.append("")
    lines.append("=" * 78)
    lines.append("总判定: " + ("PASS —— 建模 -> FEM-Eigen 计算 -> ANSYS 校核 流程已打通，结果与闭式解/商业软件一致"
                             if ok_all else "FAIL —— 存在超差项，需排查"))
    lines.append("=" * 78)
    return "\n".join(lines) + "\n", bool(ok_all)


# ---------------------------------------------------------------------------
# 5. 通用对比（自重 / 节点集中力 / 弹性支承等无闭式解工况）
# ---------------------------------------------------------------------------

def compare_generic(spec, fem: dict, adisp: dict, areac: dict, aelem: dict,
                    aspring: dict | None = None, *, stem: str,
                    note: str = "", tol: float = 1e-3) -> tuple[str, bool]:
    """FEM-Eigen vs ANSYS 全量对比，不依赖任何闭式解。

    与 `compare()` 的区别：后者用等跨满布均布荷载的 Euler-Bernoulli 闭式解
    做第三方校核，只在 CB01/CB02 那类工况成立。本函数用于自重、节点集中力、
    弹性支承等工况，判据是「两个独立求解器彼此一致 + 竖向力平衡自查」。

    `aspring`: parse_ansys_csv(<stem>_spring.csv)，{梁节点: [COMBIN14 SMISC1]}。
    """
    et = spec.elem_types[0]
    mat = {m.id: m for m in spec.materials}.get(et.mat) or spec.materials[0]
    node_xy = {int(n.id): (float(n.x), float(n.y)) for n in spec.nodes}
    elem_len = {int(e.id): math.dist(node_xy[int(e.n1)], node_xy[int(e.n2)])
                for e in spec.elements}
    total_len = max(x for x, _ in node_xy.values()) - min(x for x, _ in node_xy.values())

    sk = lambda b: float(getattr(b, "k", 0.0) or 0.0)
    springs = [b for b in spec.boundaries if sk(b) > 0.0]
    supports = sorted({int(b.node) for b in spec.boundaries
                       if sk(b) <= 0.0 and "UY" in _dof_list(b.dofs)})

    # ---- 外荷载合计（用于竖向力平衡自查） ----
    q_load = 0.0
    for el in spec.elem_loads:
        e1, e2 = int(el.e_from), int(el.e_to or el.e_from)
        q_load += sum(abs(float(el.q)) * L for eid, L in elem_len.items()
                      if e1 <= eid <= e2)
    p_load = sum(-float(ld.value) for ld in spec.nodal_loads if int(ld.dof) == 2)
    g = abs(float(getattr(spec, "gravity", 0.0) or 0.0))
    w_load = float(getattr(mat, "dens", 0.0) or 0.0) * float(et.A) * g * total_len
    total_load = q_load + p_load + w_load

    lines: list[str] = []
    ok_all = True
    lines.append("=" * 78)
    lines.append("连续梁扩展工况：BridgeStudio 前处理 -> FEM-Eigen / ANSYS 18.0 校核")
    lines.append("=" * 78)
    lines.append("算例编号      : " + stem)
    lines.append("工况          : " + (note or "（未填写）"))
    lines.append("单元 / 节点   : {} 个 2D BEAM / {} 节点，总长 {:.3f} m".format(
        len(spec.elements), len(spec.nodes), total_len))
    lines.append("材料 / 截面   : E={:.6g} Pa ; A={:.6g} m2  I={:.6g} m4  DENS={:.6g} kg/m3".format(
        mat.E, et.A, et.I, getattr(mat, "dens", 0.0)))
    lines.append("荷载          : 均布 {:.6g} N + 节点力 {:.6g} N + 自重 {:.6g} N = {:.6g} N".format(
        q_load, p_load, w_load, total_load))
    lines.append("刚性支座      : " + ", ".join(map(str, supports)))
    lines.append("弹性支承      : " + (", ".join(
        "{} K={:.6g} N/m".format(b.node, sk(b)) for b in springs) or "无"))
    lines.append("判定容差      : 相对误差 <= {:.3g}".format(tol))
    lines.append("")

    # ---- 1. 全部节点竖向位移 ----
    lines.append("-" * 78)
    lines.append("[1] 节点竖向位移 UY (m，向下为负)  FEM-Eigen vs ANSYS")
    uy = [(int(n.id), fem["disp"][int(n.id)]["v"], adisp[int(n.id)][1])
          for n in spec.nodes
          if int(n.id) in fem["disp"] and int(n.id) in adisp]
    dmax = max(abs(a - b) for _, a, b in uy)
    scale = max(abs(a) for _, a, _ in uy) or 1.0
    disp_ok = dmax <= tol * scale + 1e-9
    ok_all &= disp_ok
    lines.append("  {} 节点: 最大绝对差 {:.6e} m / 最大位移 {:.6e} m = {:.3e}  {}".format(
        len(uy), dmax, scale, dmax / scale, "PASS" if disp_ok else "FAIL"))
    for nid in sorted({1, len(spec.nodes) // 2 + 1, len(spec.nodes)}):
        row = next((r for r in uy if r[0] == nid), None)
        if row:
            lines.append("  节点 {:>3d} : FEM {:>16.8e}  ANSYS {:>16.8e}  差 {:>10.2e}".format(
                nid, row[1], row[2], abs(row[1] - row[2])))

    # ---- 2. 刚性支座竖向反力 ----
    lines.append("")
    lines.append("-" * 78)
    lines.append("[2] 刚性支座竖向反力 (N，向上为正)  FEM-Eigen vs ANSYS")
    sum_r = 0.0
    for nd in supports:
        rf = fem["reaction"].get((nd, 2), 0.0)
        ra = areac.get(nd, [0.0, 0.0])[1]
        sum_r += rf
        rel = abs(rf - ra) / max(abs(rf), 1.0)
        ok = abs(rf - ra) <= tol * max(abs(rf), 1.0)
        ok_all &= ok
        lines.append("  节点 {:<4d}  FEM {:>16.8g}  ANSYS {:>16.8g}  相对 {:.3e}  {}".format(
            nd, rf, ra, rel, "PASS" if ok else "FAIL"))

    # ---- 3. 接地弹簧反力 ----
    if springs:
        lines.append("")
        lines.append("-" * 78)
        lines.append("[3] 接地弹簧反力 (N，向上为正)")
        lines.append("  注：FEM-Eigen 把弹性支承当作自由自由度，.result 反力段不列出；")
        lines.append("      此处由 F_spring = -K*UY 反算。ANSYS COMBIN14 SMISC1 反号，比幅值。")
        for b in springs:
            u = fem["disp"].get(int(b.node), {}).get("v")
            if u is None:
                ok_all = False
                lines.append("  节点 {}: FEM 位移缺失  FAIL".format(b.node))
                continue
            f_fem = -sk(b) * (u - float(b.value))
            arow = (aspring or {}).get(int(b.node))
            f_ans = abs(arow[0]) if arow else None
            sum_r += f_fem
            if f_ans is None:
                ok_all = False
                lines.append("  节点 {:<4d}  FEM {:>16.8g}  ANSYS 缺失  FAIL".format(b.node, f_fem))
                continue
            rel = abs(f_fem - f_ans) / max(abs(f_fem), 1.0)
            ok = rel <= tol
            ok_all &= ok
            lines.append("  节点 {:<4d}  UY {:>15.8e} m  FEM {:>16.8g}  ANSYS {:>16.8g}  相对 {:.3e}  {}".format(
                b.node, u, f_fem, f_ans, rel, "PASS" if ok else "FAIL"))

    # ---- 4. 全单元端弯矩 / 剪力幅值 ----
    lines.append("")
    lines.append("-" * 78)
    lines.append("[4] 单元端内力（弯矩直接比，剪力比幅值）")
    pairs = [(abs(fem["force"][e]["M1"]), abs(aelem[e][2]),
              abs(fem["force"][e]["M2"]), abs(aelem[e][5]),
              abs(fem["force"][e]["V1"]), abs(aelem[e][1]),
              abs(fem["force"][e]["V2"]), abs(aelem[e][4]))
             for e in sorted(fem["force"]) if e in aelem]
    if pairs:
        err_m = max(max(abs(a - b), abs(c - d)) for a, b, c, d, *_ in pairs)
        err_v = max(max(abs(p[4] - p[5]), abs(p[6] - p[7])) for p in pairs)
        scale_m = max(max(p[0], p[1], p[2], p[3]) for p in pairs) or 1.0
        scale_v = max(max(p[4], p[5], p[6], p[7]) for p in pairs) or 1.0
        m_ok, v_ok = err_m / scale_m <= tol, err_v / scale_v <= tol
        ok_all &= (m_ok and v_ok)
        lines.append("  {} 单元端弯矩: 最大差 {:.6e} / 量级 {:.6e} = {:.3e}  {}".format(
            len(pairs), err_m, scale_m, err_m / scale_m, "PASS" if m_ok else "FAIL"))
        lines.append("  {} 单元端剪力幅值: 最大差 {:.6e} / 量级 {:.6e} = {:.3e}  {}".format(
            len(pairs), err_v, scale_v, err_v / scale_v, "PASS" if v_ok else "FAIL"))
        lines.append("  剪力符号约定: FEM-Eigen V 与 ANSYS SMISC 2/8 反号（属约定差异）")
    else:
        ok_all = False
        lines.append("  无可比对的单元内力  FAIL")

    # ---- 5. 竖向力平衡 ----
    lines.append("")
    lines.append("-" * 78)
    lines.append("[5] 竖向力平衡自查（刚性反力 + 弹簧反力 vs 全部外荷载）")
    bal_rel = abs(sum_r - total_load) / max(abs(total_load), 1.0)
    bal_ok = bal_rel <= tol
    ok_all &= bal_ok
    lines.append("  反力合计 {:.8g} N ; 外荷载合计 {:.8g} N ; 相对差 {:.3e}  {}".format(
        sum_r, total_load, bal_rel, "PASS" if bal_ok else "FAIL"))

    lines.append("")
    lines.append("=" * 78)
    lines.append("总判定: " + ("PASS —— FEM-Eigen 与 ANSYS 18.0 全面一致，竖向力平衡成立"
                             if ok_all else "FAIL —— 存在超差项，需排查"))
    lines.append("=" * 78)
    return "\n".join(lines) + "\n", bool(ok_all)
