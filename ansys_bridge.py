def parse_fem_result(path: Path) -> dict:
    """解析 FEM-Eigen 的 .result（节点位移/单元内力/支座反力）。"""
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    disp: dict[int, dict[str, float]] = {}
    force: dict[int, dict[str, float]] = {}
    reaction: dict[tuple[int, int], float] = {}
    section = ""
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            continue
        if line.startswith("节点位移"):
            section = "disp"
            continue
        if line.startswith("单元内力"):
            section = "force"
            continue
        if line.startswith("单元应力"):
            section = "stress"
            continue
        if line.startswith("支座反力"):
            section = "reac"
            continue
        if line.startswith("节点\t") or line.startswith("单元\t"):
            continue
        cols = line.split("\t")
        cols = [c.strip() for c in cols if c.strip() != ""]
        if not cols or not re.match(r"^\d+$", cols[0]):
            continue
        try:
            if section == "disp" and len(cols) >= 4:
                disp[int(cols[0])] = {"u": float(cols[1]), "v": float(cols[2]),
                                      "rot": float(cols[3])}
            elif section == "force" and len(cols) >= 8:
                force[int(cols[0])] = dict(zip(
                    ("N1", "N2", "V1", "M1", "V2", "M2"),
                    (float(cols[2]), float(cols[3]), float(cols[4]),
                     float(cols[5]), float(cols[6]), float(cols[7]))))
            elif section == "reac" and len(cols) >= 3:
                reaction[(int(cols[0]), int(cols[1]))] = float(cols[2])
        except ValueError:
            continue
    return {"disp": disp, "force": force, "reaction": reaction}


def parse_ansys_csv(path: Path) -> dict[int, list[float]]:
    """解析 ANSYS *VWRITE 导出的空格分隔数值文件。"""
    out: dict[int, list[float]] = {}
    for line in Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
        parts = line.split()
        if len(parts) < 2:
            continue
        try:
            vals = [float(v) for v in parts]
        except ValueError:
            continue
        key = int(round(vals[0]))
        # 只保留首次出现：防止 ANSYS 后处理重复写行时覆盖掉正确数据
        if key not in out:
            out[key] = vals[1:]
    return out


# ---------------------------------------------------------------------------
# 3. 连续梁闭式解（Euler-Bernoulli，等截面、每跨满布均布荷载）
# ---------------------------------------------------------------------------

def theory(n_spans: int, L: float, q: float, EI: float, x: float):
    """返回 (支座反力列表, 中间支座弯矩, 左跨 x 处竖向位移(向下为正)).

    仅 n_spans=2 给出逐点挠度闭式解；n_spans=3 给支座弯矩与反力。
    """
    if n_spans == 2:
        R_end, R_mid = 3.0 * q * L / 8.0, 5.0 * q * L / 4.0
        M_sup = -q * L ** 2 / 8.0
        v = q * (L ** 3 * x - 3.0 * L * x ** 3 + 2.0 * x ** 4) / (48.0 * EI)
        return [R_end, R_mid, R_end], M_sup, v, 9.0 * q * L ** 2 / 128.0
    if n_spans == 3:
        R_end, R_mid = 0.4 * q * L, 1.1 * q * L
        M_sup = -q * L ** 2 / 10.0
        # 边跨 x 处：M(x)=R_A x - q x^2/2, 叠加端部弯矩 M_B*x/L
        v = None
        return [R_end, R_mid, R_mid, R_end], M_sup, v, 0.08 * q * L ** 2
    raise ValueError("内置闭式解目前支持 2 跨 / 3 跨等跨连续梁")


