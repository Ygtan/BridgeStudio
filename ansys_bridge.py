# -*- coding: utf-8 -*-
"""BridgeStudio BridgeSpec -> ANSYS Mechanical APDL 同源导出 + 三方校核。

流程（单一数据源，避免两边手工建模产生偏差）::

    BridgeStudio  BridgeSpec
       ├── spec.to_dat()             -> <stem>.dat          FEM-Eigen 前处理输入
       ├── spec.model_dump_json()    -> <stem>.model.json   模型快照（可复现）
       └── spec_to_apdl(spec, ...)   -> <stem>.inp          ANSYS MAPDL 输入

    FEM-Eigen  example_mixed.exe     -> <stem>.result
    ANSYS 18.0 ANSYS180.exe -b       -> <stem>_disp.csv / _reac.csv / _elem.csv
    compare(...)                     -> 对比报告文本

约定（已在本机 ANSYS 18.0 / BEAM3 上实测，见 cases/*/probe 记录）:
  * ANSYS 单元 BEAM3 与 FEM-Eigen 2D BEAM 同为 Euler-Bernoulli 平面梁，
    每节点 UX / UY / ROTZ 三个自由度。
  * BEAM3 实常数 R,1,ARCT,IZZ,HEIGHT 对应 BridgeSpec 的 A / I / H。
  * ``SFBEAM,ELEM,1,PRES,q,q`` 的正 q 产生全局 -Y（向下）荷载，
    与 FEM-Eigen ``*ELEMENT_LOAD ... GY -q -q`` 一致；故取 PRES = -spec.q。
  * BEAM3 的 SMISC 序列与 BEAM4 同布局：1/2/6 = i 端 N/V/M，
    7/8/12 = j 端 N/V/M，其余为 0（2D 下无扭矩与面外分量）。

所有 APDL 注释一律用 ASCII，避免 ANSYS 在 GBK 代码页下解析中文出错。
"""
from __future__ import annotations

import math
import re
from pathlib import Path

# ---------------------------------------------------------------------------
# 1. BridgeSpec -> APDL
# ---------------------------------------------------------------------------

_DOF_MAP = {"1": "UX", "2": "UY", "3": "ROTZ"}


def _dof_list(dofs: str) -> list[str]:
    """'1-2' -> ['UX','UY']; '2' -> ['UY']; '1-3' -> ['UX','UY','ROTZ']."""
    out: list[str] = []
    for part in str(dofs).split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            out.extend(_DOF_MAP[str(i)] for i in range(int(a), int(b) + 1))
        else:
            out.append(_DOF_MAP[part])
    return out


def _num(x: float, fmt: str = "{:.10g}") -> str:
    return fmt.format(float(x))


def spec_to_apdl(spec, *, jobname: str, title: str | None = None,
                 poisson: float = 0.3) -> str:
    """把 BridgeSpec 转成可直接由 ANSYS180.exe -b 运行的 APDL 命令流。

    支持：单一 BEAM3 单元类型、水平等高梁、全局 Y 向单元均布荷载、
    节点集中力（`*CLOAD`）、自重（`ACEL` + `MP,DENS`）、UY 弹性支承
    （`BoundaryDef.k > 0` -> COMBIN14 接地弹簧）。

    弹性支承用 ANSYS 18.0 实测确认的写法：`ET,2,COMBIN14` +
    `KEYOPT,2,2,2`（2D UY 弹簧）+ `R,<n>,K`，接地节点与梁节点重合、
    `D,<ground>,ALL,0`。弹簧单元/节点号排在梁之后，后处理的 1..nnode /
    1..nelem 循环不会读到它们。不支持的工况会直接抛错，防止静默丢荷载。
    """
    errs = list(spec.validate_model() or [])
    if errs:
        raise ValueError("BridgeSpec 校验未通过: " + "; ".join(map(str, errs)))

    kinds = {str(getattr(t.kind, "value", t.kind)).upper() for t in spec.elem_types}
    if kinds != {"BEAM"} or len(spec.elem_types) != 1:
        raise ValueError("当前 APDL 导出只支持单一 BEAM 单元类型: " + repr(kinds))
    ys = {round(float(n.y), 9) for n in spec.nodes}
    if len(ys) != 1:
        raise ValueError("当前 APDL 导出只支持水平梁（所有节点 y 相同）")

    et = spec.elem_types[0]
    mat = {m.id: m for m in spec.materials}.get(et.mat) or spec.materials[0]
    node_ids = sorted(n.id for n in spec.nodes)
    elem_ids = sorted(e.id for e in spec.elements)
    if node_ids != list(range(1, len(node_ids) + 1)):
        raise ValueError("要求节点号从 1 连续编号，APDL 后处理按节点号循环")
    if elem_ids != list(range(1, len(elem_ids) + 1)):
        raise ValueError("要求单元号从 1 连续编号，APDL 后处理按单元号循环")

    nnode, nelem = len(node_ids), len(elem_ids)

    spring_k = lambda b: float(getattr(b, "k", 0.0) or 0.0)
    springs = [b for b in spec.boundaries if spring_k(b) > 0.0]
    rigid = [b for b in spec.boundaries if spring_k(b) <= 0.0]
    for b in springs:
        if _dof_list(b.dofs) != ["UY"]:
            raise ValueError("当前 APDL 导出只支持 UY 弹性支承（节点 {} dofs={}）".format(
                b.node, b.dofs))
        if abs(float(b.value)) > 0.0:
            raise ValueError("当前 APDL 导出不支持弹性支承沉降（节点 {} value={}）".format(
                b.node, b.value))

    L: list[str] = []
    add = L.append

    add("/BATCH")
    add("/TITLE," + (title or jobname))
    add("! Generated by BridgeStudio/ansys_bridge.py from ONE BridgeSpec")
    add("! Same nodes/elements/material/section/BC/loads as the FEM-Eigen .dat")
    add("/PREP7")
    add("! ---- Element type: 2D elastic beam (Euler-Bernoulli) ----")
    add("ET,1,BEAM3")
    add("! ---- Real constant: ARCT, IZZ, HEIGHT ----")
    add("R,1,{},{},{}".format(_num(et.A), _num(et.I), _num(et.H)))
    if springs:
        # ANSYS 18.0 实测：KEYOPT(2)=2 使 COMBIN14 成为 2D 竖向(UY)弹簧，
        # 与 FEM-Eigen 的 *BOUNDARY <node> 2 0 K=<k> 严格等价。
        add("! ---- Ground springs: COMBIN14 / KEYOPT(2)=2 (2D UY) ----")
        add("ET,2,COMBIN14")
        add("KEYOPT,2,2,2")
        for i, b in enumerate(springs):
            add("R,{},{}".format(2 + i, _num(spring_k(b))))
    add("! ---- Material ----")
    add("MP,EX,1,{}".format(_num(mat.E)))
    add("MP,PRXY,1,{}".format(_num(poisson)))
    if getattr(mat, "dens", None):
        add("MP,DENS,1,{}".format(_num(mat.dens)))
    if getattr(mat, "alpx", None):
        add("MP,ALPX,1,{}".format(_num(mat.alpx)))
    add("! ---- Nodes ----")
    for n in spec.nodes:
        add("N,{},{},{},0.0".format(n.id, _num(n.x), _num(n.y)))
    if springs:
        by_id = {int(n.id): n for n in spec.nodes}
        add("! ---- Ground nodes (coincident with the supported beam nodes) ----")
        for i, b in enumerate(springs):
            gn = nnode + 1 + i
            nd = by_id[int(b.node)]
            add("N,{},{},{},0.0".format(gn, _num(nd.x), _num(nd.y)))
    add("! ---- Elements ----")
    add("TYPE,1")
    add("MAT,1")
    add("REAL,1")
    for e in spec.elements:
        if e.type_id != et.id:
            raise ValueError("单元 {} 的 type_id={} 与唯一 BEAM 类型不一致".format(e.id, e.type_id))
        add("E,{},{}".format(e.n1, e.n2))
    if springs:
        add("! ---- Ground spring elements (ids follow the beam elements) ----")
        add("TYPE,2")
        add("MAT,1")
        for i, b in enumerate(springs):
            gn = nnode + 1 + i
            add("REAL,{}".format(2 + i))
            add("E,{},{}".format(gn, b.node))
    add("! ---- Boundary conditions (1=UX 2=UY 3=ROTZ) ----")
    for b in rigid:
        for dof in _dof_list(b.dofs):
            add("D,{},{},{}".format(b.node, dof, _num(b.value)))
    for i, b in enumerate(springs):
        add("D,{},ALL,0".format(nnode + 1 + i))
    add("! ---- Loads ----")
    for cl in spec.nodal_loads:
        dof = {1: "FX", 2: "FY", 3: "MZ"}.get(int(cl.dof))
        if dof is None:
            raise ValueError("不支持的节点荷载自由度: " + str(cl.dof))
        add("F,{},{},{}".format(cl.node, dof, _num(cl.value)))
    for el in spec.elem_loads:
        e1 = int(el.e_from)
        e2 = int(el.e_to) if el.e_to is not None else e1
        # FEM-Eigen: q<0 表示全局 -Y（向下）；ANSYS BEAM3 SFBEAM LKEY=1 的正
        # PRES 同样产生向下荷载（本机实测），故取 -q。
        pres = -float(el.q)
        add("*DO,EID,{},{}".format(e1, e2))
        add(" SFBEAM,EID,1,PRES,{},{}".format(_num(pres), _num(pres)))
        add("*ENDDO")
    gy = float(getattr(spec, "gravity", 0.0) or 0.0)
    if gy:
        # FEM-Eigen gy=-9.81（向下） <-> ANSYS ACEL,0,9.81,0（惯性力向下）
        add("ACEL,0.0,{},0.0".format(_num(-gy)))
    add("! ---- Solve ----")
    add("FINISH")
    add("/SOLU")
    add("ANTYPE,STATIC")
    add("SOLVE")
    add("FINISH")

    add("! ---- Post-processing: export machine-readable results ----")
    add("/POST1")
    add("SET,LAST")
    if springs:
        # ETABLE 只对 BEAM3 建表：否则 ANSYS 会对 COMBIN14 也请求 SMISC 2/6/...，
        # 每个不存在分量都给一条 WARNING（虽然输出 0 且不影响结果）。
        add("ESEL,S,ELEM,,1,{}".format(nelem))
    add("! BEAM3 SMISC: 1/2/6 = N/V/M at I, 7/8/12 = N/V/M at J")
    add("ETABLE,ENI,SMISC,1")
    add("ETABLE,EVI,SMISC,2")
    add("ETABLE,EMI,SMISC,6")
    add("ETABLE,ENJ,SMISC,7")
    add("ETABLE,EVJ,SMISC,8")
    add("ETABLE,EMJ,SMISC,12")

    # 节点位移
    add("*DIM,ADSP,ARRAY,{},4".format(nnode))
    add("*DO,I,1,{}".format(nnode))
    add(" ADSP(I,1)=I")
    add(" *GET,TMP,NODE,I,U,X")
    add(" ADSP(I,2)=TMP")
    add(" *GET,TMP,NODE,I,U,Y")
    add(" ADSP(I,3)=TMP")
    add(" *GET,TMP,NODE,I,ROT,Z")
    add(" ADSP(I,4)=TMP")
    add("*ENDDO")
    add("! *VWRITE with an array starting index writes ALL remaining rows;")
    add("! do NOT wrap it in a *DO loop (that duplicates the tail).")
    add("*CFOPEN,{}_disp,csv".format(jobname))
    add("*VWRITE,ADSP(1,1),ADSP(1,2),ADSP(1,3),ADSP(1,4)")
    add(" (1X,F8.0,3(1X,E18.10))")
    add("*CFCLOS")

    # 支座反力（BEAM3 是 2D 单元，RF,MZ 无有效定义，故只导出 FX / FY）
    add("*DIM,ARCT,ARRAY,{},3".format(nnode))
    add("*DO,I,1,{}".format(nnode))
    add(" ARCT(I,1)=I")
    add(" *GET,TMP,NODE,I,RF,FX")
    add(" ARCT(I,2)=TMP")
    add(" *GET,TMP,NODE,I,RF,FY")
    add(" ARCT(I,3)=TMP")
    add("*ENDDO")
    add("*CFOPEN,{}_reac,csv".format(jobname))
    add("*VWRITE,ARCT(1,1),ARCT(1,2),ARCT(1,3)")
    add(" (1X,F8.0,2(1X,E18.10))")
    add("*CFCLOS")

    # 单元端力
    add("*DIM,AELM,ARRAY,{},7".format(nelem))
    add("*DO,I,1,{}".format(nelem))
    add(" AELM(I,1)=I")
    add(" *GET,TMP,ELEM,I,ETAB,ENI")
    add(" AELM(I,2)=TMP")
    add(" *GET,TMP,ELEM,I,ETAB,EVI")
    add(" AELM(I,3)=TMP")
    add(" *GET,TMP,ELEM,I,ETAB,EMI")
    add(" AELM(I,4)=TMP")
    add(" *GET,TMP,ELEM,I,ETAB,ENJ")
    add(" AELM(I,5)=TMP")
    add(" *GET,TMP,ELEM,I,ETAB,EVJ")
    add(" AELM(I,6)=TMP")
    add(" *GET,TMP,ELEM,I,ETAB,EMJ")
    add(" AELM(I,7)=TMP")
    add("*ENDDO")
    add("*CFOPEN,{}_elem,csv".format(jobname))
    add("*VWRITE,AELM(1,1),AELM(1,2),AELM(1,3),AELM(1,4),AELM(1,5),AELM(1,6),AELM(1,7)")
    add(" (1X,F8.0,6(1X,E18.10))")
    add("*CFCLOS")

    if springs:
        add("ESEL,ALL")   # 弹簧单元需重新选中，下面才能 *GET 其 SMISC 1
    # 接地弹簧力（COMBIN14 SMISC 1）。FEM-Eigen 不把弹簧自由度列为硬约束，
    # .result 反力段不会输出弹簧力，只能由 K*U 反算，故单独导出供校核。
    if springs:
        add("*DIM,ASPR,ARRAY,{},2".format(len(springs)))
        for i, b in enumerate(springs, start=1):
            add(" ASPR({},1)={}".format(i, b.node))
            add(" *GET,TMP,ELEM,{},SMISC,1".format(nelem + i))
            add(" ASPR({},2)=TMP".format(i))
        add("*CFOPEN,{}_spring,csv".format(jobname))
        add("*VWRITE,ASPR(1,1),ASPR(1,2)")
        add(" (1X,F8.0,1X,E18.10)")
        add("*CFCLOS")

    add("FINISH")
    add("/EXIT,NOSAVE")
    return "\n".join(L) + "\n"


